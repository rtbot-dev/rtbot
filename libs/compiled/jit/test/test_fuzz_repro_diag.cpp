// PARITY.md class-3 regression guard for p33: before the partitioner hoisted
// Output to the tail of the LAST segment, Output was emitted in segment 0
// alongside upstream ops, never reaching the Linear sync op's then_bb that
// would populate value_map[Linear2]. Output's port-2 slot fell back to a
// zero default. The class-3 fix incidentally fixes this — Output now runs
// inside the last sync op's then_bb where every sync op's value_map entry
// is live. Hard REQUIRE so future drift fails CI.
