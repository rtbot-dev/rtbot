void run_repro(const char* tag, const char* json,
               const std::vector<TickInput>& inputs) {
  std::cout << "[diag] === " << tag << " ===\n";
  auto drive = [](rtbot::Program& p, const TickInput& tick) {
    p.send(tick.t, tick.values[0]);
  };
  rtbot::Program::set_force_interpreter_for_testing(false);
  std::vector<ParityEmission> jit_emissions;
  bool used_jit = false;
  try {
    rtbot::Program prog(json);
    used_jit = prog.using_jit();
    if (used_jit) {
      jit_emissions = drive_and_capture(prog, inputs, drive);
    }
  } catch (const std::exception& e) {
    std::cout << "[diag] " << tag << " JIT exception: " << e.what() << "\n";
  }
  if (!used_jit) {
    std::cout << "[diag] " << tag << " JIT unsupported, skipping\n";
    rtbot::Program::set_force_interpreter_for_testing(false);
    return;
  }
  rtbot::Program::set_force_interpreter_for_testing(true);
  std::vector<ParityEmission> interp_emissions;
  {
    rtbot::Program prog(json);
    interp_emissions = drive_and_capture(prog, inputs, drive);
  }
  rtbot::Program::set_force_interpreter_for_testing(false);
  dump_emissions_around_divergence(jit_emissions, interp_emissions);
}

