// Diagnostic harness for known fuzz-failure JSONs (PARITY.md "Known remaining
// divergence classes"). Each SCENARIO embeds one fuzz failure's program JSON
// and saved input ticks, drives both JIT and framework, and prints the
// emission streams side-by-side around the first divergence so the bug class
// can be identified by eye.
//
// Tag [fuzz_repro] is opt-in: ordinary CI does NOT run these scenarios, they
// are kept for hand investigation. Once a repro is diagnosed and fixed, prefer
// promoting the case to test_framework_parity_audit.cpp under its real shape
// rather than leaving the diagnostic test live.

