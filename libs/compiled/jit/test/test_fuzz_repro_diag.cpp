void dump_emissions_around_divergence(
    const std::vector<ParityEmission>& jit,
    const std::vector<ParityEmission>& interp) {
  const std::size_t n_jit = jit.size();
  const std::size_t n_interp = interp.size();
  std::cout << "[diag] jit_emissions=" << n_jit
            << " interp_emissions=" << n_interp << "\n";

  // Find first divergence index.
  std::size_t first = 0;
  const std::size_t common = std::min(n_jit, n_interp);
  bool diverged = false;
  for (; first < common; ++first) {
    const auto& a = jit[first];
    const auto& b = interp[first];
    if (a.t != b.t || a.values.size() != b.values.size()) { diverged = true; break; }
    bool vals_equal = true;
    for (std::size_t k = 0; k < a.values.size(); ++k) {
      if (dbits(a.values[k]) != dbits(b.values[k])) { vals_equal = false; break; }
    }
    if (!vals_equal) { diverged = true; break; }
  }
  if (!diverged && n_jit != n_interp) {
    diverged = true;
    first = common;
  }
  if (!diverged) {
    std::cout << "[diag] no divergence\n";
    return;
  }
  std::cout << "[diag] first divergence at index " << first << "\n";

  const std::size_t start = first > 5 ? first - 5 : 0;
  const std::size_t end_jit = std::min(n_jit, first + 6);
  const std::size_t end_interp = std::min(n_interp, first + 6);
  std::cout << "[diag] context: jit lines\n";
  for (std::size_t i = start; i < end_jit; ++i) {
    const auto& a = jit[i];
    std::cout << "  jit[" << i << "] t=" << a.t << " vals=[";
    for (std::size_t k = 0; k < a.values.size(); ++k) {
      if (k) std::cout << ", ";
      std::cout << std::setprecision(15) << a.values[k];
    }
    std::cout << "]\n";
  }
  std::cout << "[diag] context: interp lines\n";
  for (std::size_t i = start; i < end_interp; ++i) {
    const auto& b = interp[i];
    std::cout << "  interp[" << i << "] t=" << b.t << " vals=[";
    for (std::size_t k = 0; k < b.values.size(); ++k) {
      if (k) std::cout << ", ";
      std::cout << std::setprecision(15) << b.values[k];
    }
    std::cout << "]\n";
  }
  std::cout.flush();
}

